import { useState, useMemo } from 'react';
import { Button } from '@/components/ui/button';
import { Badge } from '@/components/ui/badge';
import { Input } from '@/components/ui/input';
import { Skeleton } from '@/components/ui/skeleton';
import { Select, SelectContent, SelectItem, SelectTrigger, SelectValue } from '@/components/ui/select';
import { Search, LayoutGrid, Columns, Archive, Sparkles } from 'lucide-react';
import { EditionCard } from './shared/EditionCard';
import { StatusBadge } from './shared/StatusBadge';
import { useEditions } from '../hooks/useEditions';
import { useNewsletterContext } from '../context/NewsletterContext';
import type { NewsletterEdition, EditionType, EditionStatus } from '../types/index';

const DRAFT_STATUSES: EditionStatus[] = [
  'Curating',
  'Writing',
  'In Review',
  'Approved',
  'Ready',
  'Scheduled',
  'Draft',
];

/**
 * Non-sent editions in card or kanban view.
 *
 * Requirements: 8.4, 8.5, 8.6
 */
export function DraftsQueuedTab() {
  const { editions, loading } = useEditions();
  const { setSelectedEditionId, setActiveTab } = useNewsletterContext();
  const [viewMode, setViewMode] = useState<'card' | 'kanban'>('card');
  const [typeFilter, setTypeFilter] = useState<EditionType | 'All'>('All');
  const [search, setSearch] = useState('');

  const draftEditions = useMemo(() => {
    return editions
      .filter((e) => DRAFT_STATUSES.includes(e.status))
      .filter((e) => typeFilter === 'All' || e.editionType === typeFilter)
      .filter((e) => {
        if (!search.trim()) return true;
        const q = search.toLowerCase();
        return (
          e.subject.toLowerCase().includes(q) ||
          String(e.number).includes(q)
        );
      });
  }, [editions, typeFilter, search]);

  const handleEditionClick = (edition: NewsletterEdition) => {
    setSelectedEditionId(edition.id);
    setActiveTab('today');
  };

  // Loading skeleton
  if (loading) {
    return (
      <div className="space-y-4 p-4">
        <div className="flex gap-3">
          <Skeleton className="h-8 w-32" />
          <Skeleton className="h-8 w-48" />
        </div>
        <div className="grid grid-cols-1 md:grid-cols-2 lg:grid-cols-3 gap-3">
          {Array.from({ length: 6 }).map((_, i) => (
            <Skeleton key={i} className="h-32" />
          ))}
        </div>
      </div>
    );
  }

  return (
    <div className="space-y-4 p-4">
      {/* Toolbar */}
      <div className="flex gap-3 flex-wrap items-center">
        <Select
          value={typeFilter}
          onValueChange={(v) => setTypeFilter(v as EditionType | 'All')}
        >
          <SelectTrigger className="w-36 h-8 text-xs">
            <SelectValue placeholder="Type" />
          </SelectTrigger>
          <SelectContent>
            <SelectItem value="All">All Types</SelectItem>
            <SelectItem value="Daily">Daily</SelectItem>
            <SelectItem value="Deal Alert">Deal Alert</SelectItem>
            <SelectItem value="Transfer Bonus">Transfer Bonus</SelectItem>
            <SelectItem value="Special">Special</SelectItem>
          </SelectContent>
        </Select>
        <div className="relative flex-1 max-w-xs">
          <Search className="absolute left-2 top-1/2 -translate-y-1/2 h-3.5 w-3.5 text-muted-foreground" />
          <Input
            placeholder="Search drafts..."
            value={search}
            onChange={(e) => setSearch(e.target.value)}
            className="pl-8 h-8 text-xs"
          />
        </div>
        <div className="flex gap-1 ml-auto">
          <Button
            variant={viewMode === 'card' ? 'default' : 'outline'}
            size="icon"
            className="h-8 w-8"
            onClick={() => setViewMode('card')}
          >
            <LayoutGrid className="h-3.5 w-3.5" />
          </Button>
          <Button
            variant={viewMode === 'kanban' ? 'default' : 'outline'}
            size="icon"
            className="h-8 w-8"
            onClick={() => setViewMode('kanban')}
          >
            <Columns className="h-3.5 w-3.5" />
          </Button>
        </div>
      </div>

      {/* Empty state */}
      {draftEditions.length === 0 ? (
        <div className="text-center py-12">
          <p className="text-sm text-muted-foreground">No drafts or queued editions.</p>
        </div>
      ) : viewMode === 'card' ? (
        /* Card view */
        <div className="grid grid-cols-1 md:grid-cols-2 lg:grid-cols-3 gap-3">
          {draftEditions.map((edition) => (
            <div key={edition.id} className="relative">
              {edition.autoGenerated && (
                <Badge
                  variant="secondary"
                  className="absolute -top-2 -right-2 z-10 text-[10px]"
                >
                  <Sparkles className="h-2.5 w-2.5 mr-0.5" /> Auto-generated
                </Badge>
              )}
              <EditionCard edition={edition} onClick={handleEditionClick} />
            </div>
          ))}
        </div>
      ) : (
        /* Kanban view */
        <div className="flex gap-3 overflow-x-auto pb-2">
          {DRAFT_STATUSES.map((status) => {
            const statusEditions = draftEditions.filter((e) => e.status === status);
            if (statusEditions.length === 0) return null;
            return (
              <div
                key={status}
                className="min-w-[250px] bg-muted/30 rounded-lg p-2 space-y-2"
              >
                <div className="flex items-center justify-between px-1">
                  <StatusBadge status={status} />
                  <span className="text-[10px] text-muted-foreground">
                    {statusEditions.length}
                  </span>
                </div>
                {statusEditions.map((edition) => (
                  <div key={edition.id} className="relative">
                    {edition.autoGenerated && (
                      <Badge
                        variant="secondary"
                        className="absolute -top-1 -right-1 z-10 text-[9px]"
                      >
                        <Sparkles className="h-2 w-2" />
                      </Badge>
                    )}
                    <EditionCard edition={edition} onClick={handleEditionClick} />
                  </div>
                ))}
              </div>
            );
          })}
        </div>
      )}
    </div>
  );
}
