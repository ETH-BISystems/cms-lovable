/** production: httpsCallable(functions, 'newsletterGenerateSubjectLines') */
export async function callGenerateSubjectLines(
  editionId: string,
): Promise<{ suggestions: string[] }> {
  return callFunction('newsletterGenerateSubjectLines', 'generate subject lines', () => {
    const edition = getEditionById(editionId);
    if (!edition) throw new Error(`Edition ${editionId} not found`);
    const payload: GenerateSubjectLinesInput = { editionId };
    void payload;
    const base = edition.subject.replace(/^\d+[\d,]*\s*Points?:\s*/i, '');
    return {
      suggestions: [
        base,
        `Don't miss: ${base.charAt(0).toLowerCase()}${base.slice(1)}`,
        `${base} (ends soon)`,
      ],
    };
  });
}

/** production: httpsCallable(functions, 'newsletterRewriteBlock') */
export async function callRewriteBlock(
  editionId: string,
  blockId: string,
  context: RewriteBlockInput['context'],
): Promise<{ rewrittenBody: string }> {
  return callFunction('newsletterRewriteBlock', 'rewrite block', () => {
    const edition = getEditionById(editionId);
    if (!edition) throw new Error(`Edition ${editionId} not found`);
    const block = edition.blocks.find((b) => b.id === blockId);
    if (!block) throw new Error(`Block ${blockId} not found`);
    const hints: string[] = [];
    if (context.includeVoiceNotes) hints.push('voice notes');
    if (context.includeCompetitorIntel) hints.push('competitor intel');
    if (context.includeCardData) hints.push('card data');
    const suffix =
      hints.length > 0 ? `\n\n<p><em>Rewritten with ${hints.join(', ')}.</em></p>` : '';
    return { rewrittenBody: `${block.body}${suffix}` };
  });
}

