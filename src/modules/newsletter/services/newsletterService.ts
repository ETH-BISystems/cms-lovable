// ─── Task Management ─────────────────────────────────────────────────────────

/** production: httpsCallable(functions, 'newsletterManageTasks') */
export async function callManageTasks(
  input: ManageTasksInput,
): Promise<{ taskId?: string }> {
  return callFunction('newsletterManageTasks', 'manage tasks', () => {
    const { editionId, action, taskId, taskData } = input;
    const existing = getTasks(editionId).find((t) => t.id === taskId);

    switch (action) {
      case 'create': {
        const newTaskId = mockId('task');
        const nowDate = new Date();
        const newTask: EditionTask = {
          id: newTaskId,
          title: taskData?.title ?? 'New task',
          type: taskData?.type ?? 'General',
          priority: taskData?.priority ?? 'Medium',
          status: taskData?.status ?? 'Pending',
          assignees: taskData?.assignees ?? [],
          due: taskData?.due ?? 'No date',
          blockReason: taskData?.blockReason,
          subtasks: taskData?.subtasks ?? [],
          comments: taskData?.comments ?? [],
          notes: taskData?.notes,
          createdAt: nowDate,
          updatedAt: nowDate,
        };
        putTask(editionId, newTask);
        storeEmit.tasks(editionId);
        return { taskId: newTaskId };
      }
      case 'update': {
        if (!existing) throw new Error(`Task ${taskId} not found`);
        putTask(editionId, { ...existing, ...taskData, id: existing.id, updatedAt: new Date() });
        storeEmit.tasks(editionId);
        return { taskId: existing.id };
      }
      case 'complete': {
        if (!existing) throw new Error(`Task ${taskId} not found`);
        putTask(editionId, { ...existing, status: 'Complete', updatedAt: new Date() });
        storeEmit.tasks(editionId);
        return { taskId: existing.id };
      }
      case 'block': {
        if (!existing) throw new Error(`Task ${taskId} not found`);
        putTask(editionId, {
          ...existing,
          status: 'Blocked',
          blockReason: taskData?.blockReason ?? existing.blockReason,
          updatedAt: new Date(),
        });
        storeEmit.tasks(editionId);
        return { taskId: existing.id };
      }
      case 'unblock': {
        if (!existing) throw new Error(`Task ${taskId} not found`);
        putTask(editionId, {
          ...existing,
          status: 'Pending',
          blockReason: undefined,
          updatedAt: new Date(),
        });
        storeEmit.tasks(editionId);
        return { taskId: existing.id };
      }
      case 'delete': {
        deleteTask(editionId, taskId ?? '');
        storeEmit.tasks(editionId);
        return {};
      }
      default:
        throw new Error(`Unknown task action: ${action}`);
    }
  });
}

